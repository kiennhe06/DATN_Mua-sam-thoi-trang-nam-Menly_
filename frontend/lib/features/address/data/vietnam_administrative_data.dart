/// Chuẩn hóa tên tỉnh thành từ tên cũ hoặc có tiền tố sang 34 Tỉnh/Thành phố mới
String normalizeProvince(String raw) {
  final trimmed = raw.trim();
  if (kVietnamProvinces.contains(trimmed)) return trimmed;

  if (kOldProvinceToNewMapping.containsKey(trimmed)) {
    return kOldProvinceToNewMapping[trimmed]!;
  }

  final stripped = trimmed.replaceAll(RegExp(r'^(TP\.?\s*|Thành phố\s+|Tỉnh\s+)', caseSensitive: false), '').trim();

  if (kOldProvinceToNewMapping.containsKey(stripped)) {
    return kOldProvinceToNewMapping[stripped]!;
  }

  for (final p in kVietnamProvinces) {
    final pStripped = p.replaceAll(RegExp(r'^(Thành phố\s+|Tỉnh\s+)', caseSensitive: false), '').trim();
    if (p.toLowerCase() == trimmed.toLowerCase() || pStripped.toLowerCase() == stripped.toLowerCase()) {
      return p;
    }
  }

  return kVietnamProvinces.first;
}

/// Lấy danh sách Quận / Huyện tương ứng của một Tỉnh / Thành phố
List<String> getDistrictsForProvince(String province) {
  final normalized = normalizeProvince(province);
  final list = kVietnamDistricts[normalized];
  if (list != null && list.isNotEmpty) return list;
  return kVietnamDistricts[province] ?? const [];
}

/// Lấy danh sách Phường / Xã tương ứng của một Tỉnh / Thành phố
List<String> getWardsForProvince(String province) {
  final normalized = normalizeProvince(province);
  final list = kVietnamWards[normalized];
  if (list != null && list.isNotEmpty) return list;
  return kVietnamWards[province] ?? const [];
}
